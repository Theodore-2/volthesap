create table public.charging_sessions (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips (id) on delete cascade,
  operator_name text not null,
  location_name text,
  charging_setup text not null,
  energy_kwh numeric(12, 3) not null,
  unit_price numeric(12, 4) not null,
  session_fee numeric(12, 2) not null default 0,
  total_cost numeric(14, 2) generated always as (round((energy_kwh * unit_price + session_fee)::numeric, 2)) stored,
  charged_at timestamptz,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint charging_sessions_operator_length check (char_length(operator_name) between 1 and 120),
  constraint charging_sessions_setup_allowed check (charging_setup in ('outlet', 'wallbox', 'public-ac', 'public-dc')),
  constraint charging_sessions_energy_positive check (energy_kwh > 0),
  constraint charging_sessions_prices_nonnegative check (unit_price >= 0 and session_fee >= 0),
  constraint charging_sessions_display_order_nonnegative check (display_order >= 0)
);

create table public.charging_networks (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  website_url text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint charging_networks_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint charging_networks_website_https check (website_url ~ '^https://')
);

create table public.charging_tariffs (
  id bigint generated by default as identity primary key,
  network_id bigint not null references public.charging_networks (id) on delete cascade,
  tariff_name text not null,
  connector_type text not null,
  power_min_kw numeric(8, 2),
  power_max_kw numeric(8, 2),
  unit_price_min numeric(12, 4) not null,
  unit_price_max numeric(12, 4) not null,
  idle_fee_per_minute numeric(12, 4),
  currency text not null default 'TRY',
  effective_from date,
  observed_at date not null,
  source_url text not null,
  is_location_dependent boolean not null default false,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint charging_tariffs_connector_type_allowed check (connector_type in ('AC', 'DC', 'HPC')),
  constraint charging_tariffs_power_nonnegative check (power_min_kw is null or power_min_kw >= 0),
  constraint charging_tariffs_power_order check (power_min_kw is null or power_max_kw is null or power_max_kw >= power_min_kw),
  constraint charging_tariffs_price_nonnegative check (unit_price_min >= 0 and unit_price_max >= 0),
  constraint charging_tariffs_price_order check (unit_price_max >= unit_price_min),
  constraint charging_tariffs_idle_fee_nonnegative check (idle_fee_per_minute is null or idle_fee_per_minute >= 0),
  constraint charging_tariffs_currency_format check (currency ~ '^[A-Z]{3}$'),
  constraint charging_tariffs_source_https check (source_url ~ '^https://'),
  constraint charging_tariffs_snapshot_unique unique (network_id, tariff_name, observed_at)
);

