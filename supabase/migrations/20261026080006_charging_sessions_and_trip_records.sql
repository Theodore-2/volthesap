create table public.trips (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  vehicle_id bigint references public.vehicles (id) on delete set null,
  title text not null,
  distance_km numeric(12, 2) not null,
  started_at timestamptz,
  ended_at timestamptz,
  comparison_fuel_type text,
  comparison_consumption_l_100km numeric(8, 3),
  comparison_fuel_price numeric(12, 4),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint trips_title_length check (char_length(title) between 1 and 120),
  constraint trips_distance_positive check (distance_km > 0),
  constraint trips_time_order check (started_at is null or ended_at is null or ended_at >= started_at),
  constraint trips_fuel_type_allowed check (comparison_fuel_type is null or comparison_fuel_type in ('gasoline', 'diesel')),
  constraint trips_fuel_values_nonnegative check (
    (comparison_consumption_l_100km is null or comparison_consumption_l_100km >= 0)
    and (comparison_fuel_price is null or comparison_fuel_price >= 0)
  )
);

