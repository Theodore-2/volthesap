create policy "Active charging networks are publicly readable"
on public.charging_networks for select
to anon, authenticated
using (is_active);

create policy "Active charging tariffs are publicly readable"
on public.charging_tariffs for select
to anon, authenticated
using (
  is_active
  and exists (
    select 1 from public.charging_networks
    where public.charging_networks.id = charging_tariffs.network_id
      and public.charging_networks.is_active
  )
);

